    <p>Nous ne demandons ni nom, ni adresse, ni date de naissance. Aucune donnée n'est vendue ni utilisée à des fins publicitaires.</p>

    <h2>Destinataires</h2>
    <p>Seules les équipes de PixelVerse Studios (employés et administrateur) y ont accès, selon leur rôle. Nos hébergeurs
        (alwaysdata, MongoDB Atlas) agissent comme sous-traitants et stockent les données dans l'Union européenne.</p>

    <h2>Sécurité</h2>
    <p>Connexion chiffrée (HTTPS), mots de passe hachés avec argon2id, limitation des tentatives de connexion, contrôle
        des droits sur chaque page, protection contre les failles courantes (injection SQL, XSS, CSRF).</p>

    <h2>Cookies</h2>
    <p>Un seul cookie, strictement nécessaire : le cookie de session qui vous garde connecté. Il est supprimé à la fermeture
        du navigateur. Aucun cookie de mesure d'audience ou de publicité : aucun bandeau de consentement n'est donc nécessaire.</p>

    <h2>Vos droits</h2>
    <p>Vous disposez des droits d'accès, de rectification, d'effacement, de limitation, d'opposition et de portabilité.
        Vous pouvez supprimer vous-même votre compte et toutes vos données depuis votre espace. Pour les autres demandes,
        utilisez la page <a href="/contact">Contact</a>. Vous pouvez aussi saisir la CNIL (cnil.fr).</p>
