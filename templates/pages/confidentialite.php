    <h1>Politique de confidentialité</h1>
    <p>Cette politique explique quelles données personnelles nous traitons et pourquoi, conformément au Règlement général
        sur la protection des données (RGPD).</p>

    <h2>Responsable du traitement</h2>
    <p>PixelVerse Studios (entreprise fictive), joignable par la page <a href="/contact">Contact</a>.</p>

